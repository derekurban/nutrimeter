"""Turns a taxonomy source file (wweia-2021-2023.txt) into a seed migration for food_groups, food_subgroups and
food_categories. Standard library only. Ids are slugs of the names and must stay stable once published: a later
version of the source becomes a new migration, never an edit of an applied one.

    python -I supabase/seed-sources/gen_taxonomy.py supabase/seed-sources/wweia-2021-2023.txt > migration.sql
"""
import re
import sys
import unicodedata

SOURCE = 'wweia-2021-2023'


def slug(name):
    s = unicodedata.normalize('NFKD', name).encode('ascii', 'ignore').decode()
    s = s.lower().replace('&', ' and ').replace('%', ' percent ')
    return re.sub(r'[^a-z0-9]+', '-', s).strip('-')


def q(s):
    return "'" + s.replace("'", "''") + "'"


def parse(path):
    groups, subgroups, categories = [], [], []
    group = subgroup = None
    for raw in open(path, encoding='utf-8'):
        line = raw.strip()
        if not line or (line.startswith('#') and not line.startswith(('# GROUP ', '## '))):
            continue
        if line.startswith('# GROUP '):
            name = line[len('# GROUP '):]
            group = slug(name)
            groups.append((group, name))
        elif line.startswith('## '):
            name = line[3:]
            subgroup = slug(name)
            subgroups.append((subgroup, group, name))
        else:
            m = re.match(r'^(.*?)\s*(?:\[(merged|dropped): (.*)\])?$', line)
            name, kind, detail = m.group(1), m.group(2), m.group(3)
            if kind == 'dropped':
                continue
            note = f'Merges WWEIA categories: {detail}' if kind == 'merged' else None
            categories.append((slug(name), subgroup, name, note))
    for table, rows in (('groups', groups), ('subgroups', subgroups), ('categories', categories)):
        ids = [r[0] for r in rows]
        dupes = {i for i in ids if ids.count(i) > 1}
        if dupes:
            sys.exit(f'duplicate {table} ids: {sorted(dupes)}')
    return groups, subgroups, categories


def main(path):
    sys.stdout.reconfigure(encoding='utf-8', newline='\n')
    groups, subgroups, categories = parse(path)
    out = [f'-- Generated by supabase/seed-sources/gen_taxonomy.py from {path.split("/")[-1]}. Do not edit by hand.',
           f'-- {len(groups)} groups, {len(subgroups)} subgroups, {len(categories)} categories.', '']
    out.append('insert into public.food_groups (id, name, position, source) values')
    out.append(',\n'.join(f'  ({q(i)}, {q(n)}, {k}, {q(SOURCE)})' for k, (i, n) in enumerate(groups, 1)) + ';')
    out.append('')
    out.append('insert into public.food_subgroups (id, group_id, name, position, source) values')
    out.append(',\n'.join(f'  ({q(i)}, {q(g)}, {q(n)}, {k}, {q(SOURCE)})' for k, (i, g, n) in enumerate(subgroups, 1)) + ';')
    out.append('')
    out.append('insert into public.food_categories (id, subgroup_id, name, position, source, note) values')
    out.append(',\n'.join(
        f'  ({q(i)}, {q(s)}, {q(n)}, {k}, {q(SOURCE)}, {q(note) if note else "null"})'
        for k, (i, s, n, note) in enumerate(categories, 1)) + ';')
    print('\n'.join(out))


if __name__ == '__main__':
    main(sys.argv[1])
